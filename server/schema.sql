CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, request_id VARCHAR(64) NOT NULL UNIQUE,
 reference VARCHAR(64) NOT NULL, created_at DATETIME NOT NULL, name VARCHAR(200) NOT NULL,
 company VARCHAR(200) NOT NULL, phone VARCHAR(100) NOT NULL, service VARCHAR(100) NOT NULL,
 visitor VARCHAR(64) NOT NULL, country VARCHAR(100) NOT NULL, payload LONGTEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'new', archived TINYINT NOT NULL DEFAULT 0,
 INDEX(created_at), INDEX(status), INDEX(service)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, created_at DATETIME NOT NULL,
 visitor VARCHAR(64) NOT NULL, session_id VARCHAR(64) NOT NULL, kind VARCHAR(30) NOT NULL,
 page VARCHAR(250) NOT NULL, ip VARCHAR(45) NULL, country VARCHAR(100) NOT NULL, city VARCHAR(100) NOT NULL,
 INDEX(created_at), INDEX(visitor), INDEX(kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL, actor VARCHAR(100) NOT NULL, status VARCHAR(20) NOT NULL, note TEXT NOT NULL,
 INDEX(order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS limits (
 bucket VARCHAR(100) PRIMARY KEY, hits INT NOT NULL, expires_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
